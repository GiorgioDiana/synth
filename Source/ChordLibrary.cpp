constexpr bool containsText(const char* text, const char* needle) noexcept {
    for(size_t i=0;text[i]!=0;++i) {
        size_t j=0; while(needle[j]!=0 && text[i+j]!=0 && text[i+j]==needle[j]) ++j;
        if(needle[j]==0) return true;
    }
    return false;
}
